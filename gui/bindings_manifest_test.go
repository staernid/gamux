// bindingsManifestPath is the frontend file mirroring the bound *App surface.
// The frontend IPC dispatcher (frontend/src/api/app.js) uses it to reject
// unknown methods and wrong argument counts in every environment (desktop,
// browser preview, Vitest), matching Wails v3's strict arity check.
const bindingsManifestPath = "../frontend/src/api/bindings.gen.js"

// wailsInternalMethods mirrors application.internalServiceMethods in Wails v3:
// these exported methods are lifecycle hooks and are never bound for IPC.
var wailsInternalMethods = map[string]bool{
	"ServiceName":     true,
	"ServiceStartup":  true,
	"ServiceShutdown": true,
	"ServeHTTP":       true,
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

func renderBindingsManifest(t *testing.T) []byte {
	t.Helper()
	ptrType := reflect.TypeOf((*App)(nil))
	elem := ptrType.Elem()
	ctxType := reflect.TypeOf((*context.Context)(nil)).Elem()

	type entry struct {
		js, sig string
		arity   int
	}
	var entries []entry
	for i := range ptrType.NumMethod() {
		m := ptrType.Method(i)
		if wailsInternalMethods[m.Name] {
			continue
		}
		mt := m.Type
		if mt.IsVariadic() {
			t.Fatalf("App.%s is variadic; variadic bindings are not supported by the frontend manifest", m.Name)
		}
		var ins, outs []string
		arity := 0
		for j := 1; j < mt.NumIn(); j++ { // skip receiver
			in := mt.In(j)
			if j == 1 && in.Implements(ctxType) && in.Kind() == reflect.Interface {
				continue // Wails injects context.Context; JS callers don't pass it
			}
			ins = append(ins, in.String())
			arity++
		}
		for j := 0; j < mt.NumOut(); j++ {
			outs = append(outs, mt.Out(j).String())
		}
		sig := fmt.Sprintf("(%s) -> (%s)", strings.Join(ins, ", "), strings.Join(outs, ", "))
		entries = append(entries, entry{js: lowerFirst(m.Name), sig: sig, arity: arity})
	}
	sort.Slice(entries, func(a, b int) bool { return entries[a].js < entries[b].js })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by gui/bindings_manifest_test.go; DO NOT EDIT.\n")
	buf.WriteString("// Regenerate with: make bindings\n")
	buf.WriteString("//\n")
	buf.WriteString("// Maps each bound Go method on gui.App (camelCase) to the exact number of\n")
	buf.WriteString("// arguments the frontend must pass. Wails v3 rejects calls with any other\n")
	buf.WriteString("// argument count, so the dispatcher in app.js enforces this everywhere.\n\n")
	fmt.Fprintf(&buf, "export const BINDING_PREFIX = '%s.%s.';\n\n", elem.PkgPath(), elem.Name())
	buf.WriteString("export const BINDINGS = Object.freeze({\n")
	for _, e := range entries {
		fmt.Fprintf(&buf, "  %s: %d, // %s\n", e.js, e.arity, e.sig)
	}
	buf.WriteString("});\n")
	return buf.Bytes()
}

// TestBindingsManifestUpToDate fails when bindings.gen.js drifts from the *App
// method set. Run `make bindings` (UPDATE_BINDINGS=1) to regenerate it.
func TestBindingsManifestUpToDate(t *testing.T) {
	want := renderBindingsManifest(t)
	if os.Getenv("UPDATE_BINDINGS") == "1" {
		if err := os.WriteFile(bindingsManifestPath, want, 0o644); err != nil {
			t.Fatalf("write manifest: %v", err)
		}
		return
	}
	got, err := os.ReadFile(bindingsManifestPath)
	if err != nil {
		t.Fatalf("read %s: %v (run `make bindings`)", bindingsManifestPath, err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; run `make bindings` to regenerate it", bindingsManifestPath)
	}
}

// TestFrontendCallsOnlyBoundMethods scans production frontend sources for
// AppAPI.<method> references and asserts every one is a bound *App method.
func TestFrontendCallsOnlyBoundMethods(t *testing.T) {
	ptrType := reflect.TypeOf((*App)(nil))
	bound := map[string]bool{}
	for i := range ptrType.NumMethod() {
		bound[lowerFirst(ptrType.Method(i).Name)] = true
	}

	re := regexp.MustCompile(`AppAPI\??\.([A-Za-z_][A-Za-z0-9_]*)`)
	root := "../frontend/src"
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		name := d.Name()
		isSource := strings.HasSuffix(name, ".js") || strings.HasSuffix(name, ".svelte")
		if !isSource || strings.Contains(name, ".test.") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		for _, line := range strings.Split(string(data), "\n") {
			trimmed := strings.TrimSpace(line)
			if strings.HasPrefix(trimmed, "//") || strings.HasPrefix(trimmed, "*") {
				continue
			}
			for _, m := range re.FindAllStringSubmatch(line, -1) {
				if !bound[m[1]] {
					t.Errorf("%s: AppAPI.%s is not a bound gui.App method", path, m[1])
				}
			}
		}
		return nil
	})
	if err != nil {
		t.Fatalf("walk frontend: %v", err)
	}
}
